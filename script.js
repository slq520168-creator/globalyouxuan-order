let currentLanguage = localStorage.getItem('gyx-lang') || 'zh';
const canvas = document.getElementById('stars');
const ctx = canvas.getContext('2d');
let stars = [];

function resizeStars(){
  const dpr=Math.min(window.devicePixelRatio||1,2);
  canvas.width=innerWidth*dpr;canvas.height=innerHeight*dpr;
  canvas.style.width=innerWidth+'px';canvas.style.height=innerHeight+'px';
  ctx.setTransform(dpr,0,0,dpr,0,0);
  stars=Array.from({length:Math.max(90,Math.floor(innerWidth*innerHeight/5800))},()=>({x:Math.random()*innerWidth,y:Math.random()*innerHeight,r:Math.random()*1.45+.25,a:Math.random()*.75+.18,s:Math.random()*.014+.003}));
}
function drawStars(){
  ctx.clearRect(0,0,innerWidth,innerHeight);
  for(const p of stars){p.a+=p.s;if(p.a>1||p.a<.12)p.s*=-1;ctx.beginPath();ctx.fillStyle=`rgba(83,151,255,${p.a})`;ctx.arc(p.x,p.y,p.r,0,Math.PI*2);ctx.fill();}
  requestAnimationFrame(drawStars);
}
addEventListener('resize',resizeStars);resizeStars();drawStars();

